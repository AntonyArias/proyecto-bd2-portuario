-- 01_ddl.sql | Esquema 3FN. Un solo script, se corre una vez por nodo:
--   psql -U postgres -d puerto -p 5441 -v nodo=1 -f 01_ddl.sql    (Moin)
--   psql -U postgres -d puerto -p 5442 -v nodo=2 -f 01_ddl.sql    (Limon)
--   psql -U postgres -d puerto -p 5443 -v nodo=3 -f 01_ddl.sql    (Caldera)
-- Para repetir desde cero: DROP SCHEMA puerto CASCADE;
\set ON_ERROR_STOP on
-- rango de IDs propio del nodo: nodo N usa [N*1e9, N*1e9 + 999999999]
SELECT :nodo::bigint * 1000000000 AS base, :nodo::bigint * 1000000000 + 999999999 AS tope \gset

CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE SCHEMA puerto;
SET search_path = puerto, public;

---------------------------------------------------------------------
-- CATALOGOS (iguales en los 3 nodos)
---------------------------------------------------------------------
CREATE TABLE pais (
  id_pais    SMALLINT PRIMARY KEY,
  codigo_iso CHAR(2) NOT NULL UNIQUE,
  nombre     VARCHAR(60) NOT NULL
);

CREATE TABLE tipo_contenedor (
  id_tipo_contenedor SMALLINT PRIMARY KEY,
  codigo        VARCHAR(5) NOT NULL UNIQUE,
  descripcion   VARCHAR(60) NOT NULL,
  longitud_pies SMALLINT NOT NULL CHECK (longitud_pies IN (20,40))
);

CREATE TABLE estado_contenedor (
  id_estado_contenedor SMALLINT PRIMARY KEY,
  codigo      VARCHAR(20) NOT NULL UNIQUE,
  descripcion VARCHAR(80) NOT NULL
);

CREATE TABLE tipo_inspeccion (
  id_tipo_inspeccion SMALLINT PRIMARY KEY,
  codigo      VARCHAR(20) NOT NULL UNIQUE,
  descripcion VARCHAR(100) NOT NULL
);

CREATE TABLE partida_arancelaria (
  id_partida_arancelaria SMALLINT PRIMARY KEY,
  codigo_hs        VARCHAR(10) NOT NULL UNIQUE,
  descripcion      VARCHAR(100) NOT NULL,
  tasa_arancel_pct NUMERIC(5,2) NOT NULL CHECK (tasa_arancel_pct >= 0)
);

---------------------------------------------------------------------
-- ENTIDADES COMUNES (iguales en los 3 nodos, IDs fijos)
---------------------------------------------------------------------
CREATE TABLE terminal_maritima (
  id_terminal_maritima SMALLINT PRIMARY KEY,      -- 1=Moin, 2=Limon, 3=Caldera
  codigo    VARCHAR(5) NOT NULL UNIQUE,
  nombre    VARCHAR(80) NOT NULL,
  provincia VARCHAR(40) NOT NULL
);

CREATE TABLE dependencia_aduanera (
  id_dependencia_aduanera SMALLINT PRIMARY KEY,
  id_terminal_maritima SMALLINT NOT NULL
        REFERENCES terminal_maritima ON DELETE RESTRICT,
  codigo VARCHAR(10) NOT NULL UNIQUE,
  nombre VARCHAR(80) NOT NULL
);

CREATE TABLE naviera (
  id_naviera INT PRIMARY KEY,
  id_pais    SMALLINT NOT NULL REFERENCES pais ON DELETE RESTRICT,
  nombre     VARCHAR(80) NOT NULL,
  cedula_juridica VARCHAR(15) NOT NULL UNIQUE
);

CREATE TABLE buque (
  id_buque        INT PRIMARY KEY,
  id_naviera      INT NOT NULL REFERENCES naviera ON DELETE RESTRICT,
  id_pais_bandera SMALLINT NOT NULL REFERENCES pais(id_pais) ON DELETE RESTRICT,
  nombre          VARCHAR(80) NOT NULL,
  numero_imo      CHAR(7) NOT NULL UNIQUE,
  capacidad_teu   INT NOT NULL CHECK (capacidad_teu > 0)
);

CREATE TABLE agente_aduanero (
  id_agente_aduanero INT PRIMARY KEY,
  codigo_licencia VARCHAR(12) NOT NULL UNIQUE,
  nombre          VARCHAR(60) NOT NULL,
  apellidos       VARCHAR(80) NOT NULL,
  correo          VARCHAR(100) NOT NULL UNIQUE,
  cedula_enc      BYTEA NOT NULL,     -- cifrado
  telefono_enc    BYTEA NOT NULL,     -- cifrado
  activo          BOOLEAN NOT NULL DEFAULT TRUE
);

---------------------------------------------------------------------
-- TABLAS FRAGMENTADAS (cada nodo guarda solo el subarbol de su terminal)
-- 3FN: solo manifiesto_carga lleva id_terminal_maritima; las hijas lo heredan por FK.
---------------------------------------------------------------------
CREATE TABLE manifiesto_carga (
  id_manifiesto_carga BIGINT GENERATED BY DEFAULT AS IDENTITY
        (START WITH :base MINVALUE :base MAXVALUE :tope) PRIMARY KEY,
  id_terminal_maritima SMALLINT NOT NULL
        REFERENCES terminal_maritima ON DELETE RESTRICT CHECK (id_terminal_maritima = :nodo),
  id_buque           INT NOT NULL REFERENCES buque ON DELETE RESTRICT,
  id_agente_aduanero INT NOT NULL REFERENCES agente_aduanero ON DELETE RESTRICT,
  numero_manifiesto  VARCHAR(20) NOT NULL UNIQUE,     -- MAN-T<nodo>-NNNNNN
  puerto_origen      VARCHAR(60) NOT NULL,
  fecha_arribo       TIMESTAMPTZ NOT NULL,
  fecha_registro     TIMESTAMPTZ NOT NULL DEFAULT now(),
  estado VARCHAR(20) NOT NULL DEFAULT 'REGISTRADO'
        CHECK (estado IN ('REGISTRADO','EN_DESCARGA','EN_INSPECCION','DESPACHO_PARCIAL','CERRADO'))
);

CREATE TABLE contenedor (
  id_contenedor BIGINT GENERATED BY DEFAULT AS IDENTITY
        (START WITH :base MINVALUE :base MAXVALUE :tope) PRIMARY KEY,
  id_manifiesto_carga  BIGINT NOT NULL REFERENCES manifiesto_carga ON DELETE RESTRICT,
  id_tipo_contenedor   SMALLINT NOT NULL REFERENCES tipo_contenedor ON DELETE RESTRICT,
  id_estado_contenedor SMALLINT NOT NULL DEFAULT 1 REFERENCES estado_contenedor ON DELETE RESTRICT,
  numero_iso  CHAR(11) NOT NULL UNIQUE CHECK (numero_iso ~ '^[A-Z]{4}[0-9]{7}$'),
  tara_kg     NUMERIC(10,2) NOT NULL CHECK (tara_kg > 0),
  peso_max_kg NUMERIC(10,2) NOT NULL,
  requiere_refrigeracion BOOLEAN NOT NULL DEFAULT FALSE,
  temperatura_c NUMERIC(4,1),
  CHECK (peso_max_kg > tara_kg),
  CHECK ((requiere_refrigeracion AND temperatura_c IS NOT NULL)
      OR (NOT requiere_refrigeracion AND temperatura_c IS NULL))
);

CREATE TABLE detalle_mercancia (
  id_detalle_mercancia BIGINT GENERATED BY DEFAULT AS IDENTITY
        (START WITH :base MINVALUE :base MAXVALUE :tope) PRIMARY KEY,
  id_contenedor          BIGINT NOT NULL REFERENCES contenedor ON DELETE RESTRICT,
  id_partida_arancelaria SMALLINT NOT NULL REFERENCES partida_arancelaria ON DELETE RESTRICT,
  descripcion   VARCHAR(120) NOT NULL,
  cantidad      INT NOT NULL CHECK (cantidad > 0),
  peso_kg       NUMERIC(10,2) NOT NULL CHECK (peso_kg > 0),
  valor_declarado_enc   BYTEA NOT NULL,    -- cifrado
  valor_arancelario_enc BYTEA NOT NULL,    -- cifrado
  estado_inventario VARCHAR(12) NOT NULL DEFAULT 'DISPONIBLE'
        CHECK (estado_inventario IN ('DISPONIBLE','BLOQUEADO','DESPACHADO'))
);

CREATE TABLE inspeccion_transito (
  id_inspeccion_transito BIGINT GENERATED BY DEFAULT AS IDENTITY
        (START WITH :base MINVALUE :base MAXVALUE :tope) PRIMARY KEY,
  id_contenedor      BIGINT NOT NULL REFERENCES contenedor ON DELETE RESTRICT,
  id_tipo_inspeccion SMALLINT NOT NULL REFERENCES tipo_inspeccion ON DELETE RESTRICT,
  id_agente_aduanero INT REFERENCES agente_aduanero ON DELETE RESTRICT,
  fecha_hora    TIMESTAMPTZ NOT NULL DEFAULT now(),
  resultado     VARCHAR(12) NOT NULL
        CHECK (resultado IN ('CONFORME','OBSERVACION','RETENIDO','AUTORIZADO')),
  observaciones TEXT
);

-- Indices sobre FK (PostgreSQL no los crea solo)
CREATE INDEX ix_dep_terminal    ON dependencia_aduanera(id_terminal_maritima);
CREATE INDEX ix_buque_naviera   ON buque(id_naviera);
CREATE INDEX ix_manif_buque     ON manifiesto_carga(id_buque);
CREATE INDEX ix_manif_agente    ON manifiesto_carga(id_agente_aduanero);
CREATE INDEX ix_cont_manifiesto ON contenedor(id_manifiesto_carga);
CREATE INDEX ix_cont_estado     ON contenedor(id_estado_contenedor);
CREATE INDEX ix_det_contenedor  ON detalle_mercancia(id_contenedor);
CREATE INDEX ix_det_partida     ON detalle_mercancia(id_partida_arancelaria);
CREATE INDEX ix_insp_contenedor ON inspeccion_transito(id_contenedor, fecha_hora DESC);

---------------------------------------------------------------------
-- STUB DE CIFRADO (clave solo de desarrollo). El Rol 3 reemplaza el cuerpo
-- de estas dos funciones SIN cambiar nombre ni firma.
---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION puerto.cifrar(p_texto TEXT) RETURNS BYTEA
LANGUAGE sql AS $$ SELECT pgp_sym_encrypt(p_texto, 'clave-solo-desarrollo') $$;

CREATE OR REPLACE FUNCTION puerto.descifrar(p_dato BYTEA) RETURNS TEXT
LANGUAGE sql AS $$ SELECT pgp_sym_decrypt(p_dato, 'clave-solo-desarrollo') $$;
